"""Агент «Тональность»: оценивает эмоциональный окрас обращений."""

from __future__ import annotations

from base_agent import run_agent

SYSTEM_PROMPT = """Ты эмпат с глубоким эмоциональным интеллектом. Анализируй тональность (эмоциональный окрас) текста клиента, используй 3 категории: позитивный, нейтральный, негативный. Не выдумывай. Отвечай на русском.
ВАЖНО: Используй ТОЛЬКО данные из предоставленных тикетов.
Если цифры или факты не встречаются в тикетах — не упоминай их.
Всегда указывай номер тикета как источник: (Тикет 3), (Тикеты 1, 5, 12)."""


def analyze(question: str) -> str:
    return run_agent(SYSTEM_PROMPT, question, name="агент «Тональность»")


if __name__ == "__main__":
    print(analyze("В каких категориях клиенты наиболее негативны?"))
